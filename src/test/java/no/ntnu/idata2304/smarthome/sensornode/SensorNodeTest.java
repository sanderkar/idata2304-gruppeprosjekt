package no.ntnu.idata2304.smarthome.sensornode;

import no.ntnu.idata2304.smarthome.sensornode.actuator.Heater;
import no.ntnu.idata2304.smarthome.sensornode.sensor.TemperatureSensor;
import org.junit.jupiter.api.Test;

import static org.junit.jupiter.api.Assertions.*;

public class SensorNodeTest {

  @Test
  public void idSavesAndReturnsCorrectly() {
    SensorNode node = new SensorNode(1);
    assertEquals(1, node.getNodeId());
  }

  @Test
  public void canAddAndRetrieveTemperatureSensors() {
    SensorNode node = new SensorNode(1);
    TemperatureSensor sensor1 = new TemperatureSensor(1, 25.0);
    TemperatureSensor sensor2 = new TemperatureSensor(2, 30.0);
    node.addTemperatureSensor(sensor1);
    node.addTemperatureSensor(sensor2);
    assertEquals(2, node.getTemperatureSensors().size());
    assertTrue(node.getTemperatureSensors().contains(sensor1));
    assertTrue(node.getTemperatureSensors().contains(sensor2));
  }

  @Test
  public void temperatureSensorValuesAreCorrect() {
    SensorNode node = new SensorNode(1);
    TemperatureSensor sensor = new TemperatureSensor(1, 25.0);
    node.addTemperatureSensor(sensor);
    assertEquals(25.0, node.getTemperatureSensors().get(0).getTemperature());
    sensor.setTemperature(30.0);
    assertEquals(30.0, node.getTemperatureSensors().get(0).getTemperature());
  }

  @Test
  public void returnedSensorListCannotBeModified() {
    SensorNode node = new SensorNode(1);
    TemperatureSensor sensor = new TemperatureSensor(1, 25.0);
    node.addTemperatureSensor(sensor);
    var sensors = node.getTemperatureSensors();
    assertThrows(UnsupportedOperationException.class, () -> sensors.add(new TemperatureSensor(2, 30.0)));
    assertEquals(1, node.getTemperatureSensors().size());
  }

  /**
   * Checks that the node updates each sensor exactly once, without relying on randomness.
   * Code generated by an AI, with AI assistance requested by the author.
   */
  @Test
  public void updatesEachTemperatureSensor() {
    SensorNode node = new SensorNode(1);
    CountingTemperatureSensor sensor1 = new CountingTemperatureSensor(1);
    CountingTemperatureSensor sensor2 = new CountingTemperatureSensor(2);
    node.addTemperatureSensor(sensor1);
    node.addTemperatureSensor(sensor2);

    node.updateTemperatureSensors();

    assertEquals(1, sensor1.updateCount);
    assertEquals(1, sensor2.updateCount);
  }

  /**
   * Test-only sensor that counts updates instead of generating random temperatures.
   * Code generated by an AI.
   */
  private static class CountingTemperatureSensor extends TemperatureSensor {

    private int updateCount;

    private CountingTemperatureSensor(int sensorId) {
      super(sensorId, 25.0);
    }

    @Override
    public void simulateTemperatureChange() {
      updateCount++;
    }
  }

  @Test
  public void canAddAndRetrieveHeaters() {
    SensorNode node = new SensorNode(1);
    Heater heater1 = new Heater(1);
    Heater heater2 = new Heater(2);
    node.addHeater(heater1);
    node.addHeater(heater2);
    assertEquals(2, node.getHeaters().size());
    assertTrue(node.getHeaters().contains(heater1));
    assertTrue(node.getHeaters().contains(heater2));
  }

  @Test
  public void returnedHeaterListCannotBeModified() {
    SensorNode node = new SensorNode(1);
    Heater heater = new Heater(1);
    node.addHeater(heater);
    var heaters = node.getHeaters();
    assertThrows(UnsupportedOperationException.class, () -> heaters.add(new Heater(2)));
    assertEquals(1, node.getHeaters().size());
  }

  @Test
  public void turnOnHeaterOnlyTurnsOnMatchingHeater() {
    SensorNode node = new SensorNode(1);
    Heater heater1 = new Heater(10);
    Heater heater2 = new Heater(20);
    node.addHeater(heater1);
    node.addHeater(heater2);

    boolean result = node.turnOnHeater(20);

    assertTrue(result);
    assertFalse(heater1.isOn());
    assertTrue(heater2.isOn());
  }

  @Test
  public void turnOnHeaterReturnsFalseForUnknownId() {
    SensorNode node = new SensorNode(1);
    Heater heater = new Heater(1);
    node.addHeater(heater);

    boolean result = node.turnOnHeater(2);

    assertFalse(result);
    assertFalse(heater.isOn());
  }

  @Test
  public void turnOnHeaterReturnsTrueWhenAlreadyOn() {
    SensorNode node = new SensorNode(1);
    Heater heater = new Heater(1);
    node.addHeater(heater);
    heater.turnOn();

    boolean result = node.turnOnHeater(1);

    assertTrue(result);
    assertTrue(heater.isOn());
  }

  @Test
  public void turnOffHeaterOnlyTurnsOffMatchingHeater() {
    SensorNode node = new SensorNode(1);
    Heater heater1 = new Heater(10);
    Heater heater2 = new Heater(20);
    node.addHeater(heater1);
    node.addHeater(heater2);
    heater1.turnOn();
    heater2.turnOn();

    boolean result = node.turnOffHeater(20);

    assertTrue(result);
    assertTrue(heater1.isOn());
    assertFalse(heater2.isOn());
  }

  @Test
  public void turnOffHeaterReturnsFalseForUnknownId() {
    SensorNode node = new SensorNode(1);
    Heater heater = new Heater(1);
    node.addHeater(heater);
    heater.turnOn();

    boolean result = node.turnOffHeater(2);

    assertFalse(result);
    assertTrue(heater.isOn());
  }

  @Test
  public void turnOffHeaterReturnsTrueWhenAlreadyOff() {
    SensorNode node = new SensorNode(1);
    Heater heater = new Heater(1);
    node.addHeater(heater);

    boolean result = node.turnOffHeater(1);

    assertTrue(result);
    assertFalse(heater.isOn());
  }

}
